# UI translations. Only interface text goes through _(); user-entered data
# (item names, shelves, notes, sellers, ...) is never translated.
#
# English is the source language: the English text itself is the lookup key,
# so an untranslated string simply falls back to English.

from flask import g, has_request_context, request

LANGUAGES = {
    "en": "English",
    "pt": "Português",
}
DEFAULT_LANGUAGE = "en"
LANGUAGE_COOKIE = "lang"
# Value for the <html lang> attribute
HTML_LANG = {"en": "en", "pt": "pt-PT"}


def get_language():
    # The choice is kept in a browser cookie, so it needs no database column.
    # g.language lets a request switch language before the cookie is sent back.
    if not has_request_context():
        return DEFAULT_LANGUAGE
    language = g.get("language") or request.cookies.get(LANGUAGE_COOKIE)
    if language not in LANGUAGES:
        language = DEFAULT_LANGUAGE
    # Remember it for the rest of the request, since every _() call asks again
    g.language = language
    return language


def _(text, **values):
    # Translate text and fill {placeholders} afterwards, so values such as
    # user-entered names are inserted as-is and never translated.
    if get_language() == "pt":
        text = PT.get(text, text)
    return text.format(**values) if values else text


